<p class="about-section-subtitle">Structure &amp; Sound</p>
<h2 class="about-section-title" id="organ-about-heading">パイプオルガンの説明と図</h2>
<p class="about-section-text">パイプオルガンは、ふいごが送り込む空気がパイプの中を振動させて音を出す楽器です。鍵盤を押すとバルブが開き、音栓（ストップ）の組み合わせによって音色や強さが変わります。以下の図版と解説で、音が生まれる仕組みをご覧ください。</p>
<div class="organ-diagram-layout">
<figure class="organ-diagram-figure">
<img alt="パイプオルガンの構造図（プレースホルダー）" src="<?php echo esc_url( get_template_directory_uri() ); ?>/images/oiwake_top.png" style="object-position: 42% 50%;"/>
</figure>
<div class="organ-parts-grid">
<article class="organ-part-card">
<h3>鍵盤（マニュアル・ペダル）</h3>
<p>演奏者が指や足で操作する部分です。マニュアルは手で、ペダルは足で演奏し、それぞれが異なる音域のパイプと結ばれています。</p>
</article>
<article class="organ-part-card">
<h3>パイプ</h3>
<p>音の源となる管です。材質・太さ・長さによって音色が変わり、金属パイプは明るく、木製パイプは柔らかな響きを生み出します。</p>
</article>
<article class="organ-part-card">
<h3>ふいご</h3>
<p>パイプへ一定の空気を送り込む装置です。安定した風圧が、豊かで持続的な音の支えとなります。</p>
</article>
<article class="organ-part-card">
<h3>音栓（ストップ）</h3>
<p>音色を選ぶためのレバーです。複数のストップを組み合わせることで、礼拝にふさわしいさまざまな響きを奏でます。</p>
</article>
<article class="organ-part-card">
<h3>コンソール</h3>
<p>鍵盤と音栓が集められた演奏台です。演奏者はここから、礼拝堂全体に響く音をコントロールします。</p>
</article>
